"""xAI Grok LLM API routes."""

from __future__ import annotations

import logging
from typing import Optional
from fastapi import APIRouter, Depends, HTTPException, Request, status

from app.models.user import User
from app.schemas.grok import (
    ExplainPredictionRequest,
    ExplainPredictionResponse,
    GrokChatRequest,
    GrokChatResponse,
    ReportSummaryRequest,
    ReportSummaryResponse,
)
from app.services.activity_service import get_client_ip
from app.services.grok_service import grok_service
from app.utils.dependencies import get_current_user

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/grok", tags=["xAI Grok LLM Assistant"])


def check_rate_limit(request: Request, user: Optional[User] = None) -> None:
    """Enforce per-user / per-IP rate limits (25 requests / min)."""
    client_id = f"user_{user.id}" if user else f"ip_{get_client_ip(request)}"
    if not grok_service.rate_limiter.is_allowed(client_id):
        raise HTTPException(
            status_code=status.HTTP_429_TOO_MANY_REQUESTS,
            detail="Rate limit exceeded for Grok Assistant. Please wait a moment before sending another request.",
        )


@router.post(
    "/chat",
    response_model=GrokChatResponse,
    summary="Interactive multi-lingual Q&A with Grok LLM",
)
async def chat_with_grok(
    req: GrokChatRequest,
    request: Request,
    current_user: User = Depends(get_current_user),
):
    """Interact with Grok AI assistant regarding Pneumonia, CNNs, MobileNetV2, and Grad-CAM in English or Telugu."""
    check_rate_limit(request, current_user)

    history = [{"role": m.role, "content": m.content} for m in req.messages]
    result = await grok_service.handle_general_chat(
        conversation_history=history,
        language=req.language or "en",
    )

    return GrokChatResponse(**result)


@router.post(
    "/explain-prediction",
    response_model=ExplainPredictionResponse,
    summary="Clinical Explainable AI reasoning generated by Grok",
)
async def explain_prediction_with_grok(
    req: ExplainPredictionRequest,
    request: Request,
    current_user: User = Depends(get_current_user),
):
    """Generate accessible clinical decision explanation from structured MobileNetV2 & Grad-CAM outputs."""
    check_rate_limit(request, current_user)

    norm_prob = req.normal_prob if req.normal_prob is not None else round(1.0 - req.confidence, 4)
    pneu_prob = req.pneumonia_prob if req.pneumonia_prob is not None else round(req.confidence, 4)

    result = await grok_service.explain_prediction(
        prediction=req.prediction,
        confidence=req.confidence,
        normal_prob=norm_prob,
        pneumonia_prob=pneu_prob,
        model_version=req.model_version or "2.1.0-alpha",
        uncertainty=req.uncertainty or 0.0,
        validation_status=req.validation_status or "PASSED",
        has_gradcam=bool(req.has_gradcam),
        language=req.language or "en",
    )

    return ExplainPredictionResponse(**result)


@router.post(
    "/report-summary",
    response_model=ReportSummaryResponse,
    summary="Generate natural-language summary for medical reports",
)
async def generate_report_summary_with_grok(
    req: ReportSummaryRequest,
    request: Request,
    current_user: User = Depends(get_current_user),
):
    """Produce concise, natural language clinical summary paragraph for PDF documentation."""
    check_rate_limit(request, current_user)

    summary_text = await grok_service.generate_report_summary(
        prediction=req.prediction,
        confidence=req.confidence,
        normal_prob=req.normal_prob,
        pneumonia_prob=req.pneumonia_prob,
        filename=req.filename,
        uncertainty=req.uncertainty or 0.0,
        validation_status=req.validation_status or "PASSED",
        language=req.language or "en",
    )

    return ReportSummaryResponse(
        summary=summary_text,
        language=req.language or "en",
    )

